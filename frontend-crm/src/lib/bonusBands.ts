/**
 * Отрисовка комиссионной сетки менеджера (полос).
 *
 * Источник правды по ставкам — бэкенд (backend/src/common/bonus-bands.ts).
 * Здесь только форматирование: сетка приходит с сервера и здесь НЕ
 * дублируется — иначе ставки разъедутся между релизами фронта и бэка.
 *
 * Комиссия считается ПО ПОЛОСЕ, не прогрессивно: весь месячный объём
 * умножается на ставку одной полосы (объём 200 000 → 6% → 12 000).
 */

/**
 * Подпись диапазона полосы: «0 – 75 000 TJS», у последней — «300 001+ TJS».
 * Обе границы включительные, поэтому печатаем ровно те числа, что заданы в
 * сетке, без «до/менее»: менеджер должен видеть свой порог посимвольно.
 */
export function bandRangeLabel(
  minAmount: number,
  maxAmount: number | null,
  currency?: string,
): string {
  const n = (v: number) => v.toLocaleString('ru-RU');
  const suffix = currency ? ` ${currency}` : '';
  if (maxAmount === null) return `${n(minAmount)}+${suffix}`;
  return `${n(minAmount)} – ${n(maxAmount)}${suffix}`;
}
