@Controller('knowledge')
export class KnowledgeController {
  @Get()
  index() {
    return KNOWLEDGE.categories.map((c) => ({
      slug: c.slug,
      title: c.title,
      icon: c.icon,
      summary: c.summary,
      articleCount: c.articles.length,
    }));
  }

  @Get(':slug')
  byCategory(@Param('slug') slug: string) {
    return KNOWLEDGE.categories.find((c) => c.slug === slug) || null;
  }
}
