/**
 * Длины номера БЕЗ кода страны, которые считаем осмысленными.
 *
 * Только 9 — национальная часть +992 (TJ), она же UZ/KG/AZ/GE. Так в базу
 * попадают импорт и записи «901234567» от менеджера. Десятизначный «голый»
 * номер (РФ без кода) сюда СПЕЦИАЛЬНО не входит: ровно этой длины бывает
 * «+992 1234567» из случая (б) в шапке файла, и дать ей ключ значит вернуть
 * ту самую ошибку. Цена — российский номер, записанный без +7, партнёрским
 * поиском не находится; это пропуск, а не ложное начисление.
 */
const BARE_NATIONAL_LENGTHS: ReadonlyArray<number> = [9];

/** Разобранный номер: код страны отделён от национальной части. */
export type PhoneIdentity = {
  /** Только цифры, без международного префикса набора «00». */
  digits: string;
  /** Код страны, если он распознан ОДНОЗНАЧНО. null — номер записан без кода. */
  countryCode: string | null;
  /** Национальная часть — то, что осталось после кода страны. */
  national: string;
};

/**
 * Разбирает номер на код страны + национальную часть.
 *
 * Возвращает null, когда однозначного разбора НЕТ — и это штатный, самый
 * важный ответ функции. Так отвечают: пустая строка, обрывок номера,
 * 10–11 цифр, не ложащиеся ни на один код из белого списка («+992 1234567»),
 * и теоретическая строка, подходящая сразу под два кода. Вызывающий обязан
 * трактовать null как «сопоставлять нечем», а не как «искать по пустому».
 */
export function parsePhoneIdentity(phone: string | null | undefined): PhoneIdentity | null {
  if (typeof phone !== 'string') return null;
  let digits = phone.replace(/\D/g, '');
  // «00» — это международный префикс набора, тот же «+», записанный цифрами.
  // Снимаем его, иначе «00992901234567» не ляжет ни на один код страны.
  if (digits.startsWith('00')) digits = digits.slice(2);
  if (!digits) return null;

  // Собираем ВСЕ подходящие разборы, а не первый попавшийся: два разбора
  // означают, что номер записан неоднозначно, и угадывать здесь нельзя.
  const parses: Array<{ cc: string; national: string }> = [];
  for (const entry of COUNTRY_CODES) {
    if (!digits.startsWith(entry.cc)) continue;
    const national = digits.slice(entry.cc.length);
    if (!entry.nationalLengths.includes(national.length)) continue;
    parses.push({ cc: entry.cc, national });
  }

  if (parses.length === 1) {
    return { digits, countryCode: parses[0].cc, national: parses[0].national };
  }
  // Неоднозначно — отказываемся. На нынешнем белом списке недостижимо
  // (проверено по длинам), но список будут править, а тихая ошибка здесь
  // стоит денег.
  if (parses.length > 1) return null;

  // Кода страны нет. Принимаем только длину, которая не может быть
  // «код + короткий номер» — см. инвариант у COUNTRY_CODES.
  if (BARE_NATIONAL_LENGTHS.includes(digits.length)) {
    return { digits, countryCode: null, national: digits };
  }
  return null;
}

/**
 * Один ли это номер. ЕДИНСТВЕННОЕ место, где принимается решение о совпадении.
 *
 * Правило:
 *   • национальные части совпадают ЦЕЛИКОМ (не хвостами, длина в длину);
 *   • коды стран равны — либо хотя бы у одной стороны кода нет вовсе.
 *
 * Второе условие и есть починка случая (а): «+998 90 123 45 67» и
 * «+992 90 123 45 67» дают одинаковую национальную часть, но оба кода
 * известны и различны → это разные люди. А «901234567» из импорта по-прежнему
 * находит «+992901234567»: кода нет только у одной стороны, спорить не с чем.
 */
export function phonesMatch(a: string | null | undefined, b: string | null | undefined): boolean {
  const left = parsePhoneIdentity(a);
  const right = parsePhoneIdentity(b);
  if (!left || !right) return false;
  if (left.national !== right.national) return false;
  if (left.countryCode && right.countryCode) return left.countryCode === right.countryCode;
  return true;
}

/**
 * Грубый пред-фильтр для SQL: последние 9 цифр разобранного номера.
 * Пустая строка — «сопоставление невозможно», запрос делать не нужно.
 *
 * ПОЧЕМУ ЭТО КОРРЕКТНО КАК ПРЕД-ФИЛЬТР (условие необходимое, но НЕ
 * достаточное — решает всегда phonesMatch на прочитанных строках):
 *   • национальная часть 9 и длиннее → совпадение по phonesMatch влечёт
 *     совпадение последних 9 цифр тривиально;
 *   • национальная часть 8 (TM/MN/AM) бывает только с кодом страны, а
 *     phonesMatch в этом случае требует ОДИНАКОВЫЙ код → последние 9 цифр
 *     («последняя цифра кода» + номер) снова совпадают;
 *   • «голый» номер короче 9 цифр ключа не получает вовсе.
 * То есть ни одно настоящее совпадение пред-фильтром не отсекается.
 *
 * Разбор идёт первым специально: строка «+992 1234567» из случая (б) хвост бы
 * дала, а ключа не заслуживает, и лишний запрос по ней делать незачем.
 */
export function phoneMatchPrefilterTail(phone: string | null | undefined): string {
  const identity = parsePhoneIdentity(phone);
  if (!identity) return '';
  // parsePhoneIdentity гарантирует минимум 9 цифр (см. инвариант у
  // COUNTRY_CODES и BARE_NATIONAL_LENGTHS), так что slice всегда полон.
  return identity.digits.slice(-PHONE_TAIL_LENGTH);
}

/**
 * Номер для лога. Телефон — персональные данные, в журнал уходят только
 * последние 4 цифры: их хватает, чтобы сверить строку лога с карточкой
 * клиента, и не хватает, чтобы восстановить номер из логов.
 */
export function maskPhoneForLog(phone: string | null | undefined): string {
  if (typeof phone !== 'string') return '—';
  const digits = phone.replace(/\D/g, '');
  if (digits.length < 4) return '—';
  return `***${digits.slice(-4)}`;
}
