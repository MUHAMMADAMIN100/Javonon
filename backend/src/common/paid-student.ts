import { Prisma } from '@prisma/client';

/**
 * КТО СЧИТАЕТСЯ СТУДЕНТОМ. Решение учредителя: студент — это тот, кто
 * ОПЛАТИЛ. Пока оплаты нет, человек остаётся заявкой и в раздел «Студенты»,
 * в отчёт по студентам и в счётчики дашборда/KPI не попадает.
 *
 * «Оплатил» = есть хотя бы один ДЕЙСТВУЮЩИЙ приход категории
 * TUITION_PAYMENT. Отменённый (сторнированный, reversedAt != null) платёж не
 * считается: раньше фильтр его засчитывал, и человек, чью единственную
 * оплату отменили, продолжал числиться студентом.
 *
 * Одно определение на всех: список, статистика и KPI обязаны давать одно и
 * то же число — иначе карточка «Студентов: 120» над списком из 95 строк.
 *
 * Выпадающие списки выбора студента (сделка, платёж, группа) этот фильтр НЕ
 * применяют намеренно: первый платёж новому студенту надо к кому-то
 * привязать, а оплатившим он станет только после него.
 */
const PAID_TRANSACTION: Prisma.TransactionWhereInput = {
  type: 'INCOME',
  category: 'TUITION_PAYMENT',
  reversedAt: null,
};

/** where-условие «оплативший студент». */
export const PAID_STUDENT_WHERE: Prisma.StudentWhereInput = {
  transactions: { some: PAID_TRANSACTION },
};

/** where-условие «ещё не оплатил» (служебные сверки). */
export const UNPAID_STUDENT_WHERE: Prisma.StudentWhereInput = {
  transactions: { none: PAID_TRANSACTION },
};
