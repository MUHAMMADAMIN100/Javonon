function escapeRe(s: string): string {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

// Иборҳо (калидҳои дорои фосила) — аз дарозтарин ба кӯтоҳтарин, то ки
// «два раза в год» пеш аз «раз в год» мувофиқат кунад.
const PHRASE_KEYS = Object.keys(TERMS)
  .filter((k) => k.indexOf(' ') !== -1)
  .sort((a, b) => b.length - a.length);

const PHRASE_RE = PHRASE_KEYS.length
  ? new RegExp(PHRASE_KEYS.map(escapeRe).join('|'), 'giu')
  : null;

const WORD_RE = /[\p{L}\p{M}]+/gu;

/** Ҳарфи калон/хурди матни аслиро нигоҳ медорад. */
function matchCase(source: string, out: string): string {
  if (!out) return out;
  const upper = source.toUpperCase();
  const lower = source.toLowerCase();
  if (source === upper && source !== lower) return out; // СШA → ИМА
  const first = source.charAt(0);
  if (first === first.toUpperCase() && first !== first.toLowerCase()) {
    return out.charAt(0).toUpperCase() + out.slice(1);
  }
  return out.charAt(0).toLowerCase() + out.slice(1);
}

/**
 * Қимати матнии барномаро ба тоҷикӣ табдил медиҳад.
 * Калимаҳои ношинос (лотинӣ, номи донишгоҳ, рақам) бетағйир мемонанд.
 * Барои матни холӣ `null` бармегардонад — Row/JSX онро намоиш намедиҳад.
 */
export function toTajik(value: string | number | null | undefined): string | null {
  if (value === null || value === undefined) return null;
  const src = String(value).trim();
  if (!src) return null;

  let out = src;
  if (PHRASE_RE) {
    out = out.replace(PHRASE_RE, (m) => matchCase(m, TERMS[m.toLowerCase()] ?? m));
  }
  out = out.replace(WORD_RE, (m) => {
    const hit = TERMS[m.toLowerCase()];
    return hit ? matchCase(m, hit) : m;
  });
  return out;
}
